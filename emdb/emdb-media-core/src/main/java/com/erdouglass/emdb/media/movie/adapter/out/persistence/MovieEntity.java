package com.erdouglass.emdb.media.movie.adapter.out.persistence;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.Optional;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.SequenceGenerator;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import jakarta.persistence.Version;

import com.erdouglass.emdb.media.kernel.LanguageCode;
import com.erdouglass.emdb.media.kernel.Overview;
import com.erdouglass.emdb.media.kernel.SourceId.Source;
import com.erdouglass.emdb.media.kernel.Title;

/// The persistent row behind a movie aggregate.
///
/// A flat projection of the aggregate: the details are inlined as columns rather
/// than mapped as an embeddable, and value objects are stored as their
/// underlying primitives. Nothing here enforces a domain rule — invariants are
/// re-applied when [MovieCommandAdapter] rebuilds the aggregate.
///
/// Optional fields are exposed through getters returning `Optional` so that
/// mapping code cannot silently dereference an absent value, while the fields
/// themselves stay nullable for the provider.
///
/// Column lengths are taken from the value objects rather than restated, so the
/// schema and the domain cannot drift apart.
///
/// Two unique constraints protect identity: one on the surrogate id, one on the
/// TMDB id — the latter is what makes ingestion an upsert rather than a source
/// of duplicates under concurrency.
@Entity 
@Table(
  name = "movie",
  uniqueConstraints = {
    @UniqueConstraint(name = "uq_movie_surrogate_id", columnNames = { "surrogate_id" }),
    @UniqueConstraint(name = "uq_movie_source_id", columnNames = { "source", "source_id" }),
  }
)
class MovieEntity {
  
  /// The primary key is generated by a database sequence upon insertion. It is
  /// URL friendly making it easy for users to discover and link to content.
  @Id
  @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "movie_seq")
  @SequenceGenerator(name = "movie_seq", sequenceName = "movie_seq", initialValue = 1, allocationSize = 1)
  private Long id;
    
  @Column(name = "original_language", length = LanguageCode.LENGTH)
  private String originalLanguage;
  
  @Column(length = Overview.MAX_LENGTH)
  private String overview;
  
  @Column(name = "release_date")
  private LocalDate releaseDate;
  
  @Column(name = "score", precision = 5, scale = 3)
  private BigDecimal score;
  
  @Enumerated(EnumType.STRING)
  @Column(length = Source.MAX_LENGTH)
  private Source source;
  
  @Column(name = "source_id", nullable = false, length = 64)
  private String sourceId;
  
  /// Internal surrogate id, time based UUID7, generated by the application that 
  /// never gets exposed to the public.
  @Column(name = "surrogate_id", nullable = false, updatable = false)
  private UUID surrogateId;
  
  @Column(nullable = false, length = Title.MAX_LENGTH)
  private String title;
  
  @Version
  private Long version;
  
  MovieEntity() {}

  public void setId(Long id) { this.id = id; }
  public Long getId() { return id; }
  
  public void setOriginalLanguage(String originalLanguage) { this.originalLanguage = originalLanguage; }
  public Optional<String> getOriginalLanguage() { return Optional.ofNullable(originalLanguage); }
  
  public void setOverview(String overview) { this.overview = overview; }
  public Optional<String> getOverview() { return Optional.ofNullable(overview); }
  
  public void setReleaseDate(LocalDate releaseDate) { this.releaseDate = releaseDate; }
  public Optional<LocalDate> getReleaseDate() { return Optional.ofNullable(releaseDate); }
  
  public void setScore(BigDecimal score) { this.score = score; }
  public Optional<BigDecimal> getScore() { return Optional.ofNullable(score); }
  
  public void setSource(Source source) { this.source = source; }
  public Source getSource() { return source; }
  
  public void setSourceId(String sourceId) { this.sourceId = sourceId; }
  public String getSourceId() { return sourceId; }
  
  public void setSurrogateId(UUID surrogateId) { this.surrogateId = surrogateId; }
  public UUID getSurrogateId() { return surrogateId; }
  
  public void setTitle(String title) { this.title = title; }
  public String getTitle() { return title; }
  
  public void setVersion(long version) { this.version = version; }
  public Long getVersion() { return version; }
}
