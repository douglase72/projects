package com.erdouglass.emdb.media.person.adapter.out.persistence;

import java.time.LocalDate;
import java.util.Optional;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.SequenceGenerator;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import jakarta.persistence.Version;

import com.erdouglass.emdb.media.SourceId.Source;
import com.erdouglass.emdb.media.person.domain.Biography;
import com.erdouglass.emdb.media.person.domain.Gender;
import com.erdouglass.emdb.media.person.domain.Name;

@Entity 
@Table(
  name = "person",
  uniqueConstraints = {
    @UniqueConstraint(name = "uq_person_surrogate_id", columnNames = { "surrogate_id" }),
    @UniqueConstraint(name = "uq_person_source_id", columnNames = { "source", "source_id" }),
  }
)
class PersonEntity {
  
  @Column(length = Biography.MAX_LENGTH)
  private String biography;
  
  @Column(name = "birth_date")
  private LocalDate birthDate;
    
  @Column(name = "death_date")
  private LocalDate deathDate;
  
  @Enumerated(EnumType.STRING)
  @Column(length = Gender.MAX_LENGTH)
  private Gender gender;
  
  /// The primary key is generated by a database sequence upon insertion. It is
  /// URL friendly making it easy for users to discover and link to content.
  @Id
  @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "person_seq")
  @SequenceGenerator(name = "person_seq", sequenceName = "person_seq", initialValue = 1, allocationSize = 1)
  private Long id;
  
  @Column(nullable = false, length = Name.MAX_LENGTH)
  private String name;
  
  @Enumerated(EnumType.STRING)
  @Column(length = Source.MAX_LENGTH)
  private Source source;
  
  @Column(name = "source_id", nullable = false, length = 64)
  private String sourceId;
  
  /// Internal surrogate id, time based UUID7, generated by the application that 
  /// never gets exposed to the public.
  @Column(name = "surrogate_id", nullable = false, updatable = false)
  private UUID surrogateId;
  
  @Version
  private Long version;
  
  /// Default constructor required by JPA.
  PersonEntity() {}
  
  public void setBiography(String biography) { this.biography = biography; }
  public Optional<String> getBiography() { return Optional.ofNullable(biography); }
  
  public void setBirthDate(LocalDate birthDate) { this.birthDate = birthDate; }
  public Optional<LocalDate> getBirthDate() { return Optional.ofNullable(birthDate); }
  
  public void setDeathDate(LocalDate deathDate) { this.deathDate = deathDate; }
  public Optional<LocalDate> getDeathDate() { return Optional.ofNullable(deathDate); }
  
  public void setGender(Gender gender) { this.gender = gender; }
  public Optional<Gender> getGender() { return Optional.ofNullable(gender); }
  
  public void setId(Long id) { this.id = id; }
  public Long getId() { return id; }
  
  public void setName(String name) { this.name = name; }
  public String getName() { return name; }
  
  public void setSource(Source source) { this.source = source; }
  public Source getSource() { return source; }
  
  public void setSourceId(String sourceId) { this.sourceId = sourceId; }
  public String getSourceId() { return sourceId; }
  
  public void setSurrogateId(UUID surrogateId) { this.surrogateId = surrogateId; }
  public UUID getSurrogateId() { return surrogateId; }
  
  public void setVersion(long version) { this.version = version; }
  public Long getVersion() { return version; }
}